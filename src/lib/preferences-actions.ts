"use server";

/**
 * Preference server actions (SRS §6.2–6.4, §12).
 *
 * Every action enforces:
 *   1. User is authenticated with the correct role.
 *   2. PREFERENCES phase is OPEN.
 *   3. User has completed their profile (profileCompletedAt is set).
 *   4. The submitted ids exist in the pool with the expected count.
 *
 * Saves are wipe-and-replace inside a transaction so the user's preferences
 * are always consistent on disk — never half-rank.
 *
 * `User.preferencesSubmittedAt` is set ONLY by `markPreferencesSubmitted`, not
 * by the per-task saves. This is used for FCFS in project assignment, so we
 * only stamp it once the user explicitly commits the whole bundle.
 */

import { z } from "zod";
import type { Prisma } from "@prisma/client";

import { db } from "@/lib/db";
import { getConfig } from "@/lib/config";
import {
  ForbiddenError,
  requireAuth,
  requireParticipant,
  requirePhase
} from "@/lib/permissions";

const idArray = z.array(z.string().min(1));

function requireDistinct(ids: string[]): string[] {
  const set = new Set(ids);
  if (set.size !== ids.length) {
    throw new Error("Duplicate selections are not allowed.");
  }
  return ids;
}

async function gate(role: "AGENT" | "POD_HEAD" | "ORCH") {
  await requirePhase("PREFERENCES", "OPEN");
  const user = await requireParticipant(role);
  if (!user.profileCompletedAt) {
    throw new ForbiddenError("Complete your profile first.");
  }
  return user;
}

// === Agent ranks Pod Heads ===

export async function saveAgentRankings(podHeadIds: string[]): Promise<void> {
  const user = await gate("AGENT");
  const config = await getConfig();
  const ids = requireDistinct(idArray.parse(podHeadIds));
  if (ids.length !== config.agentRanksTopNPodHeads) {
    throw new Error(
      `Rank exactly ${config.agentRanksTopNPodHeads} Pod Heads (got ${ids.length}).`
    );
  }

  // Pool validation: every id must be a real PodHeadProfile.
  const podHeads = await db.podHeadProfile.findMany({
    where: { id: { in: ids } },
    select: { id: true }
  });
  if (podHeads.length !== ids.length) {
    throw new Error("Some ranked Pod Heads no longer exist.");
  }

  const agent = await db.agentProfile.findUniqueOrThrow({
    where: { userId: user.id },
    select: { id: true }
  });

  await db.$transaction([
    db.agentPodHeadRanking.deleteMany({ where: { agentId: agent.id } }),
    db.agentPodHeadRanking.createMany({
      data: ids.map((podHeadId, i) => ({
        agentId: agent.id,
        podHeadId,
        rank: i + 1,
        autoGenerated: false
      }))
    })
  ]);
}

