// === Final submit: stamps preferencesSubmittedAt (used for FCFS) ===

interface SubmitStatus {
  ok: boolean;
  missing: string[]; // task names the user hasn't finished
}

export async function markPreferencesSubmitted(): Promise<SubmitStatus> {
  await requirePhase("PREFERENCES", "OPEN");
  const user = await requireAuth();
  if (!user.profileCompletedAt) {
    throw new ForbiddenError("Complete your profile first.");
  }
  const missing = await collectMissingTasks({ id: user.id, role: user.role });
  if (missing.length > 0) {
    return { ok: false, missing };
  }
  // Idempotent: only stamp the first time (FCFS uses this timestamp).
  await db.user.update({
    where: { id: user.id, preferencesSubmittedAt: null },
    data: { preferencesSubmittedAt: new Date() }
  }).catch(() => {
    // already submitted — fine
  });
  return { ok: true, missing: [] };
}

// Helper: which tasks does this user still owe?
async function collectMissingTasks(user: {
  id: string;
  role: "AGENT" | "POD_HEAD" | "ORCH";
}): Promise<string[]> {
  const config = await getConfig();
  const missing: string[] = [];

  if (user.role === "AGENT") {
    const agent = await db.agentProfile.findUnique({
      where: { userId: user.id },
      select: { id: true }
    });
    if (!agent) return ["agent profile"];
    const count = await db.agentPodHeadRanking.count({
      where: { agentId: agent.id }
    });
    if (count !== config.agentRanksTopNPodHeads) missing.push("rank Pod Heads");
  } else if (user.role === "POD_HEAD") {
    const ph = await db.podHeadProfile.findUnique({
      where: { userId: user.id },
      select: { id: true }
    });
    if (!ph) return ["pod head profile"];
    const [orchs, agents, projects] = await Promise.all([
      db.podHeadOrchRanking.count({ where: { podHeadId: ph.id } }),
      db.podHeadAgentSelection.count({ where: { podHeadId: ph.id } }),
      db.podHeadProjectPick.count({ where: { podHeadId: ph.id } })
    ]);
    if (orchs !== config.orchCount) missing.push("rank Orchs");
    if (agents !== config.podHeadRanksTopNAgents) missing.push("rank Agents");
    if (projects !== config.projectsPerPodHead) missing.push("pick Projects");
  } else if (user.role === "ORCH") {
    const orch = await db.orchProfile.findUnique({
      where: { userId: user.id },
      select: { id: true }
    });
    if (!orch) return ["orch profile"];
    const count = await db.orchPodHeadSelection.count({
      where: { orchId: orch.id }
    });
    if (count !== config.podHeadsPerOrch) missing.push("rank Pod Heads");
  }

  return missing;
}

